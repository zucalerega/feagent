"""Illustration of the scoring + ranking pipeline with scripted pseudo-agents.

NOT real agents: each "agent" is the scripted reference pipeline at some mesh level, optionally
with a deliberate mistake, and its token / wall-time usage is an assumed number.  Solver runs,
QoI measurements, gates and scores are real.  Writes docs/population-demo.md.

    python examples/population_demo.py
"""

from __future__ import annotations

import json
import re
import shutil
import sys
from pathlib import Path

from feabench.evaluate import evaluate_submission
from feabench.paths import REPO_ROOT
from feabench.scoring import ScoreConfig, population_summary
from feabench.suites.verification import run_reference

CASES = ["lame_sphere", "torsion_shaft", "cantilever_tip_load", "nafems_le10"]
# name: (mesh level, assumed agent usage, mistake)
AGENTS = {
    "careful": (3, {"input_tokens": 150_000, "cache_read_tokens": 900_000, "output_tokens": 15_000, "wall_s": 300}, None),
    "quick": (1, {"input_tokens": 60_000, "cache_read_tokens": 300_000, "output_tokens": 6_000, "wall_s": 120}, None),
    "overkill": (5, {"input_tokens": 400_000, "cache_read_tokens": 3_000_000, "output_tokens": 40_000, "wall_s": 1500}, None),
    "unit_slip": (3, {"input_tokens": 150_000, "cache_read_tokens": 900_000, "output_tokens": 15_000, "wall_s": 300}, "E in Pa"),
    "load_slip": (3, {"input_tokens": 150_000, "cache_read_tokens": 900_000, "output_tokens": 15_000, "wall_s": 300}, "load x0.1"),
}


def mutate(deck: str, mistake: str | None) -> str:
    if mistake == "E in Pa":
        return re.sub(r"\*ELASTIC\n([0-9.e+]+)", lambda m: f"*ELASTIC\n{float(m.group(1)) * 1e6:g}", deck)
    if mistake == "load x0.1":
        out, in_load = [], False
        for ln in deck.splitlines():
            if ln.startswith("*"):
                in_load = ln.upper().startswith(("*DLOAD", "*CLOAD"))
            elif in_load:
                parts = ln.split(",")
                parts[-1] = f" {float(parts[-1]) * 0.1:.12g}"
                ln = ",".join(parts)
            out.append(ln)
        return "\n".join(out) + "\n"
    return deck


def main(work: Path = Path("/tmp/feabench-demo")):
    cfg = ScoreConfig.for_model("claude-opus-5-5")
    shutil.rmtree(work, ignore_errors=True)
    results, rows = [], []
    for case in CASES:
        decks = {}
        for name, (level, usage, mistake) in AGENTS.items():
            if level not in decks:
                rep = run_reference(case, level, work / "ref")
                decks[level] = (work / "ref" / f"{case}_L{level}" / "model.inp").read_text()
            sub = work / name / case
            sub.mkdir(parents=True, exist_ok=True)
            (sub / "model.inp").write_text(mutate(decks[level], mistake))
            rep = evaluate_submission(f"verification/{case}", sub, agent_cost=usage, cfg=cfg)
            s = rep["summary"]
            failed_gates = [g for g, ok in s["gates"].items() if not ok]
            results.append({"agent": name, "case": case, **s})
            rows.append(f"| {case} | {name} | {s['score']:.3f} | {'yes' if s['gates_passed'] else 'no: ' + ', '.join(failed_gates)} "
                        f"| {s['accuracy']:.3f} | {s['efficiency']:.2f} | ${s['cost_usd']:.2f} | {s['n_equations']} |")
            print(rows[-1], flush=True)
    pop = population_summary(results, cost_cap=cfg.cost_max_usd)
    per_agent = {a: sum(r["score"] for r in results if r["agent"] == a) / len(CASES) for a in AGENTS}
    md = ["# Population demo (scripted pseudo-agents)", "",
          "Generated by `examples/population_demo.py`. **Not real agents:** every \"agent\" is the scripted",
          "reference pipeline at a fixed mesh level, two of them with a deliberate mistake, and the token",
          "and wall-time numbers are assumptions. The solver runs, measured QoIs, gates and scores are real",
          "(ccx 2.21, Claude Opus 5.5 list prices).", "",
          "| Agent | Mesh level | Assumed usage | Mistake |", "|---|---|---|---|"]
    for name, (level, usage, mistake) in AGENTS.items():
        md.append(f"| {name} | {level} | {usage['input_tokens'] // 1000}k in + {usage['cache_read_tokens'] // 1000}k cached, "
                  f"{usage['output_tokens'] // 1000}k out, {usage['wall_s']} s | {mistake or '-'} |")
    md += ["", "| Case | Agent | S | Gates | A | E | Cost | Equations |", "|---|---|---|---|---|---|---|---|"] + rows
    md += ["", "## Population summary", "", "| Agent | Mean S | Bradley-Terry rating |", "|---|---|---|"]
    for a in sorted(AGENTS, key=lambda a: -pop["ratings"][a]):
        md.append(f"| {a} | {per_agent[a]:.3f} | {pop['ratings'][a]:+.2f} |")
    md += ["", f"* pass rate {pop['pass_rate']:.2f}, coverage {pop['coverage']:.2f}, "
               f"gate-failure rate {pop['gate_failure_rate']:.2f}",
           "* Pareto front per case (accuracy vs cost, cheapest first): "
           + "; ".join(f"{c}: {', '.join(f)}" for c, f in pop["pareto_front"].items()),
           f"* hypervolume (mean over cases) {pop['hypervolume']:.3f}, median cost ${pop['median_cost_usd']:.2f}", ""]
    out = REPO_ROOT / "docs" / "population-demo.md"
    out.write_text("\n".join(md))
    (work / "results.json").write_text(json.dumps(results, indent=1, default=float))
    print(out)


if __name__ == "__main__":
    main(Path(sys.argv[1]) if len(sys.argv) > 1 else Path("/tmp/feabench-demo"))
