#!/usr/bin/env python
"""harness_hex mesh system: the harness's gmsh, hexahedra where they work, tets with Netgen otherwise.

    build.py PART_STEP AXIS OUT_DIR --purpose linear|nonlinear [--h H] [--max-nodes N]

linear     tet10 through the stock harness path (`feagent.mesher.run_mesh`, Netgen + HighOrder
           optimisation): feacore/skfem cannot solve hexahedra (feacore/solver/_skfem_mesh.py), so the
           linear deliverable is tets. Gates: the harness's own `assess_mesh`.
nonlinear  all-hex (C3D8) by tet -> Netgen-optimised tet mesh -> `Mesh.SubdivisionAlgorithm=2` (each tet
           becomes 4 hexes), boundary nodes projected back onto the CAD, interior Laplacian smoothing
           guarded by the scaled Jacobian. Falls back to a straight-sided tet10 mesh (labelled in
           report.json) if no hex candidate is valid. Gates: hex-applicable subset of the harness gates.

Deterministic (fixed gmsh threads). Needs the repo's venv: `uv run --extra pardiso python build.py ...`.
"""
from __future__ import annotations

import argparse
import json
import os
import sys
import time
from pathlib import Path

os.environ.setdefault("CUDA_VISIBLE_DEVICES", "")
os.environ.setdefault("OMP_NUM_THREADS", "4")
os.environ.setdefault("MKL_NUM_THREADS", "4")

import gmsh  # noqa: E402
import numpy as np  # noqa: E402
import yaml  # noqa: E402

from feagent import gmsh_util as gu  # noqa: E402
from feagent import mesher  # noqa: E402
from feagent.gates import failed, passed, skipped, threshold_gate  # noqa: E402
from feagent.geometry import analyze  # noqa: E402
from feagent.gmsh_session import gmsh_session  # noqa: E402
from feagent.quality import assess_mesh  # noqa: E402
from feagent.spec import QualitySpec, load_spec  # noqa: E402
from feagent.types import Gate  # noqa: E402

SYSTEM = "harness_hex"
AXES = {"x": 0, "y": 1, "z": 2}
# defaults per purpose: (global h, thin-wall layers); tuned so the linear mesh lands in 50k-400k DOF
# and the hex mesh near the 40k-node budget (see README)
DEFAULT_H = {"linear": 0.005, "nonlinear": 0.0045}
HEX_H_CANDIDATES = (0.010, 0.008, 0.0065, 0.006, 0.0055, 0.005, 0.0045, 0.004, 0.0035, 0.003)
HEX_MIN_SJ = 0.10          # a candidate is "valid" above this minimum scaled Jacobian (corner values)
HEX_NODE_BUDGET = 40_000
SMOOTH_ITERS = 40


# ------------------------------------------------------------------------------------------------
# spec

def write_spec(step: Path, axis: str, out: Path, purpose: str, h: float, curvature: int | None = None) -> Path:
    """mesh.yaml next to the outputs: planar faces at the two axis extremes, selected by geometry."""
    geo = analyze(step, tessellate=False)
    a = AXES[axis]
    lo, hi = geo.bbox[0][a], geo.bbox[1][a]
    pad = 1e-4 * geo.diag

    def slab(pos: float) -> list[list[float]]:
        b0 = [-10 * geo.diag] * 3
        b1 = [10 * geo.diag] * 3
        b0[a], b1[a] = pos - pad, pos + pad
        return [b0, b1]

    def normal(sign: int) -> list[float]:
        n = [0.0, 0.0, 0.0]
        n[a] = float(sign)
        return n

    # top: part 3 has one face, part 65 two (contract); expect is checked by the harness
    expect_top = 2 if step.parent.parent.name.startswith("abc_00000065") else 1
    hexp = purpose == "nonlinear"
    spec = {
        "name": f"{SYSTEM}_{purpose}", "geometry": os.path.relpath(step.resolve(), out.resolve()),
        "analysis": "fea",
        "groups": {
            "bottom": {"select": {"kind": "plane", "normal": normal(-1), "box": slab(lo)}, "expect": 1},
            "top": {"select": {"kind": "plane", "normal": normal(+1), "box": slab(hi)}, "expect": expect_top},
        },
        "size": {"global": h, "min": h / 8, "curvature": curvature or (8 if hexp else 12), "thin_wall_layers": 1 if hexp else 2},
        "element": {"order": 1 if hexp else 2, "optimize": "netgen"},
        "export": ["msh", "inp"],
    }
    out.mkdir(parents=True, exist_ok=True)
    p = out / "mesh.yaml"
    p.write_text("# generated by experiments/mesh_systems/harness_hex/build.py\n" + yaml.safe_dump(spec, sort_keys=False))
    return p


