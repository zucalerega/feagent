# hex by subdivision

_NEXT = np.array([1, 2, 3, 0, 5, 6, 7, 4])
_PREV = np.array([3, 0, 1, 2, 7, 4, 5, 6])
_VERT = np.array([4, 5, 6, 7, 0, 1, 2, 3])        # the node above (bottom) / below (top)
_SIGN = np.array([1, 1, 1, 1, -1, -1, -1, -1.0])  # keeps det positive for gmsh hex8 ordering


def hex_corner_sj(p: np.ndarray, hexes: np.ndarray) -> np.ndarray:
    """Scaled Jacobian at the 8 corners of each hex8: (n, 8); > 0 everywhere = valid."""
    x = p[hexes]                                     # (n, 8, 3)
    e1 = x[:, _NEXT] - x
    e2 = x[:, _PREV] - x
    e3 = x[:, _VERT] - x
    det = np.einsum("nci,nci->nc", np.cross(e1, e2), e3) * _SIGN
    den = np.linalg.norm(e1, axis=2) * np.linalg.norm(e2, axis=2) * np.linalg.norm(e3, axis=2)
    return det / np.maximum(den, 1e-300)


def _mesh_arrays() -> tuple[np.ndarray, np.ndarray, np.ndarray, np.ndarray]:
    """(node tags, coords, hex8 rows (into coords), hex element tags) of the current model."""
    ntags, xyz, lookup = gu.node_table()
    rows, etags = [], []
    for _, vt in gmsh.model.getEntities(3):
        for _, et, nodes in gu.element_blocks(3, vt, (5,)):
            rows.append(lookup[nodes])
            etags.append(et)
    return ntags, xyz, np.concatenate(rows), np.concatenate(etags)


def _project_boundary(ntags: np.ndarray, xyz: np.ndarray) -> np.ndarray:
    """Move curve and surface nodes onto the CAD (subdivision puts new ones at edge midpoints)."""
    xyz = xyz.copy()
    lookup = {int(t): i for i, t in enumerate(ntags)}
    for dim in (1, 2):
        for _, ent in gmsh.model.getEntities(dim):
            nt, _, _ = gmsh.model.mesh.getNodes(dim, ent, includeBoundary=False)
            for t in nt:
                i = lookup[int(t)]
                cp, _ = gmsh.model.getClosestPoint(dim, ent, list(xyz[i]))
                xyz[i] = cp
    return xyz


def _interior_nodes(ntags: np.ndarray) -> np.ndarray:
    lookup = {int(t): i for i, t in enumerate(ntags)}
    out = []
    for _, vt in gmsh.model.getEntities(3):
        nt, _, _ = gmsh.model.mesh.getNodes(3, vt, includeBoundary=False)
        out += [lookup[int(t)] for t in nt]
    return np.array(sorted(out), np.int64)


def _smooth(xyz: np.ndarray, hexes: np.ndarray, interior: np.ndarray) -> np.ndarray:
    """Interior Laplacian smoothing, each sweep kept only if the minimum corner SJ does not drop."""
    n = len(xyz)
    ei = np.concatenate([hexes[:, a] for a in range(8)])
    ej = np.concatenate([hexes[:, _NEXT[a]] for a in range(8)])
    ek = np.concatenate([hexes[:, _VERT[a]] for a in range(8)])
    src = np.concatenate([ei, ej, ei, ek])
    dst = np.concatenate([ej, ei, ek, ei])
    is_int = np.zeros(n, bool)
    is_int[interior] = True
    keep = is_int[src]
    src, dst = src[keep], dst[keep]
    cnt = np.bincount(src, minlength=n).astype(float)
    best = hex_corner_sj(xyz, hexes).min()
    for _ in range(SMOOTH_ITERS):
        acc = np.zeros_like(xyz)
        np.add.at(acc, src, xyz[dst])
        new = xyz.copy()
        m = is_int & (cnt > 0)
        new[m] = 0.5 * xyz[m] + 0.5 * acc[m] / cnt[m, None]
        q = hex_corner_sj(new, hexes).min()
        if q < best - 1e-12:
            break
        xyz, best = new, max(best, q)
    return xyz


def _set_nodes(ntags: np.ndarray, xyz: np.ndarray) -> None:
    for t, x in zip(ntags, xyz):          # keeps entity classification untouched
        gmsh.model.mesh.setNode(int(t), list(map(float, x)), [])


def _tet_mesh(h: float) -> None:
    gmsh.model.mesh.clear()
    gmsh.option.setNumber("Mesh.SubdivisionAlgorithm", 0)   # generate() would subdivide by itself
    gmsh.option.setNumber("Mesh.MeshSizeMax", h)
    gmsh.option.setNumber("Mesh.MeshSizeMin", h / 8)
    gmsh.option.setNumber("Mesh.Algorithm3D", 1)
    gmsh.model.mesh.generate(3)
    gmsh.model.mesh.optimize("Netgen")


def hex_candidate(h: float, project: bool = True, smooth: bool = True) -> dict:
    """Mesh at base tet size h, subdivide to hexes, return stats; the mesh stays in the session."""
    _tet_mesh(h)
    gmsh.option.setNumber("Mesh.SubdivisionAlgorithm", 2)
    gmsh.model.mesh.refine()
    ntags, xyz, hexes, _ = _mesh_arrays()
    raw = hex_corner_sj(xyz, hexes).min()
    if project:
        xyz = _project_boundary(ntags, xyz)
    proj = hex_corner_sj(xyz, hexes).min()
    if smooth:
        xyz = _smooth(xyz, hexes, _interior_nodes(ntags))
    _set_nodes(ntags, xyz)
    return {"h": h, "n_nodes": len(ntags), "n_hex": len(hexes), "sj_raw": float(raw),
            "sj_projected": float(proj), "sj_final": float(hex_corner_sj(xyz, hexes).min())}


STATE: dict = {"candidates": [], "chosen": None, "kind": "hex", "h0": None, "fixed_h": False}


def _generate_hex(spec) -> None:
    """Replaces `feagent.mesher._generate`: choose the largest base h whose hex mesh is valid and
    within the node budget; else the cheapest valid one; else fall back to straight tets (labelled)."""
    cands = [spec.size.global_] if STATE["fixed_h"] else list(HEX_H_CANDIDATES)
    for h in cands:
        try:
            c = hex_candidate(h)
        except Exception as e:  # a gmsh failure is a rejected candidate, not a crash
            STATE["candidates"].append({"h": h, "error": str(e)[:200]})
            continue
        STATE["candidates"].append(c)
        print(f"hex candidate {c}", file=sys.stderr, flush=True)
        if c["sj_final"] >= HEX_MIN_SJ:      # first valid candidate (largest base h) wins; stays in session
            STATE["chosen"] = c
            return
    STATE["kind"] = "tet10-fallback"
    _tet_mesh(spec.size.global_)
    gmsh.model.mesh.setOrder(2)
    gmsh.model.mesh.optimize("HighOrder")


