# gates for a hex mesh (the harness gates are tet-only: n/a ones are reported as skipped)

def hex_report(msh: Path, res, q: QualitySpec) -> dict:
    with gmsh_session():
        gmsh.open(str(msh))
        ntags, xyz, hexes, etags = _mesh_arrays()
        qual = gu.element_qualities(etags, ("minSICN", "minSJ"))
        sj = hex_corner_sj(xyz, hexes)
        vol_mesh = gu.integrated_measure(3)
        areas = {f: gu.integrated_measure(2, f) for f in gu.entity_tags(2)}
        # connectivity: node-sharing components of the hex mesh
        from scipy.sparse import coo_matrix
        from scipy.sparse.csgraph import connected_components
        a = np.repeat(hexes[:, :1], 8, axis=1).ravel()
        g = coo_matrix((np.ones(a.size), (a, hexes.ravel())), shape=(len(xyz),) * 2)
        ncomp = connected_components(g, directed=False)[0]
        vols = [v for v in res.geometry.volumes]
    v_cad = float(sum(v.volume for v in vols))
    verr = abs(vol_mesh - v_cad) / v_cad
    garea = {}
    for name, gr in res.groups.items():
        if gr.dim == 2:
            m = sum(areas.get(t, 0.0) for t in gr.tags)
            garea[name] = (float(gr.area), float(m), abs(m - gr.area) / gr.area)
    worst = max(garea.items(), key=lambda kv: kv[1][2])
    n_inv = int((qual["minSJ"] <= 0).sum())
    gates: list[Gate] = [
        threshold_gate("inverted", "No inverted elements", float(n_inv), 0.0,
                       message_fmt="{n} of {m} hexes have non-positive scaled Jacobian (min SJ {sj:.3g}; "
                       "worst corner SJ {cj:.3g})", n=n_inv, m=len(hexes), sj=float(qual["minSJ"].min()),
                       cj=float(sj.min()), hint="smooth or coarsen the base tet mesh"),
        threshold_gate("sicn", "Minimum SICN", float(qual["minSICN"].min()), q.min_sicn, worse="below",
                       message_fmt="min SICN {value:.3f} (threshold {limit}); median {med:.3f} "
                       "(gmsh hex SICN)", med=float(np.median(qual["minSICN"])), hint="smooth the mesh"),
        skipped("gamma", "Minimum gamma", "n/a for hexahedra (inscribed/circumscribed radius is tet-only)"),
        threshold_gate("volume_fidelity", "Volume fidelity", verr, q.max_volume_error,
                       message_fmt="mesh volume {m:.6g} vs CAD {c:.6g}: relative error {value:.3g} "
                       "(threshold {limit})", m=vol_mesh, c=v_cad, hint="raise curvature / lower size"),
        threshold_gate("area_fidelity", "Group area fidelity", worst[1][2], q.max_area_error,
                       message_fmt="worst group '{g}': mesh area {m:.6g} vs CAD {c:.6g}, relative "
                       "error {value:.3g} (threshold {limit})", g=worst[0], m=worst[1][1], c=worst[1][0],
                       hint="refine"),
        (passed if ncomp == len(vols) else failed)(
            "connectivity", "Mesh connectivity",
            f"mesh has {ncomp} node-connected component(s), geometry expects {len(vols)}",
            float(ncomp), float(len(vols))),
        skipped("thin_wall", "Thin-wall resolution", "n/a: hexes from subdivided tets; thin walls were "
                "refined at the tet stage (>= 2 hexes through a wall that has >= 1 tet layer)"),
    ]
    stats = lambda a: {"min": float(a.min()), "p01": float(np.percentile(a, 1)),  # noqa: E731
                       "median": float(np.median(a)), "mean": float(a.mean()), "max": float(a.max())}
    quality = {"n_nodes": len(xyz), "n_hexes": len(hexes), "sicn": stats(qual["minSICN"]),
               "sj": stats(qual["minSJ"]), "corner_sj_min": float(sj.min()), "inverted": n_inv,
               "volume_cad": v_cad, "volume_mesh": vol_mesh, "volume_error": verr,
               "group_area": {k: list(v) for k, v in garea.items()}, "components": int(ncomp),
               "expected_components": len(vols)}
    return {"gates": gates, "quality": quality, "sicn_per_cell": qual["minSICN"],
            "points": xyz, "cells": hexes}


def render_hex(points, hexes, sicn, out_png: Path) -> str:
    """The harness's quality render (render.render_quality) with a hexahedron grid."""
    import pyvista as pv
    from feagent import render
    from feagent.meshdata import MeshData

    def grid(mesh):
        n = len(mesh.tets)
        cells = np.hstack([np.full((n, 1), 8), mesh.tets]).astype(np.int64).ravel()
        return pv.UnstructuredGrid(cells, np.full(n, pv.CellType.HEXAHEDRON, np.uint8),
                                   np.asarray(mesh.points, float))

    md = MeshData(points=points, tets=hexes, tet_tags=np.arange(len(hexes)), tet_volume=np.zeros(len(hexes)),
                  tris={}, tri_face={}, volume_groups={}, order=1)
    old = render._grid
    render._grid = grid
    try:
        r = render.render_quality(md, sicn, out_png)
    finally:
        render._grid = old
    return r.caption.replace("tets", "hexes")


# ------------------------------------------------------------------------------------------------

def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("step")
    ap.add_argument("axis", choices=list(AXES))
    ap.add_argument("out")
    ap.add_argument("--purpose", choices=("linear", "nonlinear"), required=True)
    ap.add_argument("--h", type=float, default=None, help="global tet size [m]; nonlinear: fixes the base size")
    ap.add_argument("--thin-factor", type=float, default=None,
                    help="harness THIN_WALL_SIZE_FACTOR for the tet stage (default 0.8 linear, 1.4 hex)")
    ap.add_argument("--curvature", type=int, default=None, help="elements per 2*pi (default 12 linear, 8 hex)")
    ap.add_argument("--no-hex", action="store_true", help="nonlinear: skip hexes, straight tet10 (netgen)")
    a = ap.parse_args(argv)
    step, out = Path(a.step), Path(a.out)
    t0 = time.perf_counter()
    h = a.h or DEFAULT_H[a.purpose]
    spec_path = write_spec(step, a.axis, out, a.purpose, h, a.curvature)
    mesher.THIN_WALL_SIZE_FACTOR = a.thin_factor or (1.4 if a.purpose == "nonlinear" else 0.8)
    use_hex = a.purpose == "nonlinear" and not a.no_hex
    STATE["fixed_h"] = a.h is not None
    spec = load_spec(spec_path)
    if use_hex:
        mesher._generate = _generate_hex
    else:
        STATE["kind"] = "tet10" if a.purpose == "linear" else "tet-nohex"
    # one gmsh thread count for determinism
    orig_apply = mesher._apply_options

    def apply(run):
        orig_apply(run)
        gmsh.option.setNumber("General.NumThreads", 4)

    mesher._apply_options = apply
    res = mesher.run_mesh(spec, out_dir=out / "out")
    if not res.ok:
        print(json.dumps(res.to_dict(), indent=1, default=str)[:3000])
        return 1
    msh = Path(res.mesh_path)
    build_s = time.perf_counter() - t0
    extra: dict = {}
    if use_hex and STATE["kind"] == "hex":
        rep = hex_report(msh, res, spec.quality)
        gates = list(res.gates) + rep["gates"]
        quality = rep["quality"]
        caption = render_hex(rep["points"], rep["cells"], rep["sicn_per_cell"], out / "mesh.png")
        order, etype, n_el = 1, "hex8 (C3D8)", len(rep["cells"])
        extra = {"hex_candidates": STATE["candidates"], "hex_chosen": STATE["chosen"]}
    else:
        q = assess_mesh(msh, res, spec.quality, "fea", "netgen")
        gates = list(res.gates) + list(q.gates)
        quality = {k: v for k, v in q.to_dict().items() if k != "gates"}
        from feagent.meshdata import read_msh
        from feagent.render import render_quality
        caption = render_quality(read_msh(msh), q.sicn_per_tet, out / "mesh.png").caption
        order, etype, n_el = res.order, "tet10 (C3D10)", q.n_tets
        if STATE["kind"] == "tet10-fallback":
            extra = {"hex_candidates": STATE["candidates"],
                     "note": "no valid hex candidate; straight-sided tet10 fallback"}
    status = "fail" if any(g.status == "fail" for g in gates) else "pass"
    report = {
        "schema_version": 1, "system": SYSTEM, "part": step.parent.parent.name.rsplit("_bc", 1)[0],
        "purpose": a.purpose, "element": etype, "mesh_kind": STATE["kind"], "n_nodes": res.n_nodes,
        "n_elements": n_el, "order": order, "dofs": 3 * res.n_nodes, "build_s": round(time.perf_counter() - t0, 2),
        "status": status, "gates": [g.to_dict() for g in gates], "quality": quality,
        "render_caption": caption, "groups": {k: {"faces": v.tags, "elements": v.elements} for k, v in res.groups.items()},
        **extra,
    }
    (out / "report.json").write_text(json.dumps(report, indent=1))
    for f in ("mesh.msh", "mesh.inp"):
        src = Path(res.out_dir) / f
        (out / f).write_bytes(src.read_bytes())
    print(f"{report['part']} {a.purpose}: {report['mesh_kind']} {etype} nodes={res.n_nodes} "
          f"elements={n_el} dofs={report['dofs']} gates={status} build={report['build_s']}s")
    return 0 if status == "pass" else 2


if __name__ == "__main__":
    sys.exit(main())
