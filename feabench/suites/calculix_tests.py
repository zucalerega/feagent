"""CalculiX upstream regression suite (``test/`` directory of the ccx source tree).

What the references are (and are not): each ``<deck>.dat.ref`` is CalculiX's *own* output
from the version that produced the suite.  Passing means "this ccx build reproduces upstream
ccx to 0.1 % of each output block's maximum", i.e. solver/build verification -- not an
independent check of the physics.  We use the suite to (a) accept a solver build as the
fixed solver for the swarm, and (b) as a corpus of known-good decks per keyword.

Upstream source: https://github.com/Dhondtguido/CalculiX (Guido Dhondt, GPL-2.0).
The ``test/`` directory first appears in commit 3e742ab (2023-12-02), four months after the
2.21 release (99ef753) and before 2.22; it is the closest snapshot to the 2.21 binary.
"""

from __future__ import annotations

import json
import re
import shutil
import subprocess
from concurrent.futures import ThreadPoolExecutor, as_completed
from pathlib import Path

from ..ccx.dat import compare_dat
from ..ccx.inp import scan_deck
from ..ccx.runner import ccx_version, run_ccx

UPSTREAM = {
    "repo": "https://github.com/Dhondtguido/CalculiX",
    "commit": "3e742abb894ce071206c2a3836dac80dfbaaf9d0",
    "commit_date": "2023-12-02",
    "path": "test",
    "license": "GPL-2.0-or-later",
}

# decks the upstream `compare` script skips (generated by other decks)
SKIP = {"circ10pcent.rfn", "circ10p.rfn", "segmentsmooth.rfn", "segmentsmooth2.rfn"}
# upstream compares the .mtx (substructure matrix) for these instead of the .dat
MTX_AS_DAT = {"substructure", "substructure2"}
# restart-read decks and the deck whose .rout they need (inferred from names; best effort)
RESTART_PRODUCER = {
    "beamread": "beamwrite",
    "beamread2": "beamwrite2",
    "beamread3": "beamwrite3",
    "beamread4": "beamwrite",
    "beamhtfc2": "beamhtfc",
}


def fetch(dest: str | Path, commit: str = UPSTREAM["commit"]) -> Path:
    """Sparse, blob-filtered clone of upstream ``test/`` at the pinned commit."""
    dest = Path(dest)
    if not (dest / ".git").exists():
        subprocess.run(
            ["git", "clone", "--filter=blob:none", "--no-checkout", UPSTREAM["repo"], str(dest)], check=True
        )
    subprocess.run(["git", "-C", str(dest), "sparse-checkout", "set", "--no-cone", "/test/*", "/LICENSE"], check=True)
    subprocess.run(["git", "-C", str(dest), "checkout", "-q", commit], check=True)
    return dest / "test"


def list_decks(test_dir: str | Path) -> list[str]:
    test_dir = Path(test_dir)
    names = sorted(p.stem for p in test_dir.glob("*.inp"))
    return [n for n in names if n not in SKIP and not n.endswith(".rfn")]


def _dependencies(deck: Path) -> list[str]:
    """Files named by INPUT= parameters (submodel/include) of a deck."""
    deps = []
    for line in deck.read_text(errors="replace").splitlines():
        if line.lstrip().startswith("*") and not line.lstrip().startswith("**"):
            for m in re.finditer(r"INPUT\s*=\s*\"?([^,\"\s]+)", line, re.I):
                deps.append(m.group(1))
    return deps


def _run_one(name: str, test_dir: Path, work_root: Path, timeout: float, tol: float) -> dict:
    src = test_dir / f"{name}.inp"
    wd = work_root / name
    if wd.exists():
        shutil.rmtree(wd)
    wd.mkdir(parents=True)
    shutil.copy(src, wd / src.name)
    missing = []
    for dep in _dependencies(src):
        cand = [test_dir / dep, work_root / Path(dep).stem / dep]
        cand += [work_root / Path(dep).name.split(".")[0] / dep]
        found = next((c for c in cand if c.exists()), None)
        if found:
            shutil.copy(found, wd / dep)
        else:
            missing.append(dep)
    if name in RESTART_PRODUCER:
        rout = work_root / RESTART_PRODUCER[name] / f"{RESTART_PRODUCER[name]}.rout"
        if rout.exists():
            shutil.copy(rout, wd / f"{name}.rin")
        else:
            missing.append(f"{name}.rin")
    info = scan_deck(wd / src.name)
    rec: dict = {"deck": name, "tags": info.tags(), "element_types": info.element_types,
                 "procedures": info.procedures, "n_nodes": info.n_nodes, "n_elements": info.n_elements,
                 "inp_bytes": src.stat().st_size, "missing_inputs": missing}
    try:
        rr = run_ccx(wd / src.name, timeout=timeout, threads=1)
    except Exception as exc:  # pragma: no cover - environment problems
        rec.update(status="error", error=str(exc))
        return rec
    rec.update(cpu_s=round(rr.cpu_s, 3), wall_s=round(rr.wall_s, 3), max_rss_mb=round(rr.max_rss_mb, 1),
               returncode=rr.returncode, timed_out=rr.timed_out, ccx_errors=rr.errors[:3],
               n_equations=rr.n_equations)
    dat = wd / f"{name}.dat"
    if name in MTX_AS_DAT and (wd / f"{name}.mtx").exists():
        dat = wd / f"{name}.mtx"
    ref = test_dir / f"{name}.dat.ref"
    cmp = compare_dat(dat, ref, tol=tol)
    # Stricter than upstream `compare`: a deck whose solver run errored is not a pass even if
    # its (possibly empty) .dat happens to match, and an empty reference verifies nothing.
    if rr.timed_out:
        status = "timeout"
    elif rr.returncode != 0 or rr.errors:
        status = "solver_error"
    elif cmp.status == "pass" and ref.exists() and ref.stat().st_size == 0:
        status = "pass_vacuous"
    else:
        status = cmp.status
    rec.update(status=status, dat_status=cmp.status,
               max_rel_block_error=cmp.max_rel_block_error,
               worst_line=cmp.line, worst_value=cmp.value, worst_reference=cmp.reference)
    return rec


def verify(test_dir: str | Path, work_root: str | Path, out_json: str | Path | None = None,
           workers: int = 4, timeout: float = 900.0, tol: float = 1e-3, only: list[str] | None = None,
           progress: bool = True) -> dict:
    """Run every deck with the installed ccx and compare .dat with .dat.ref (datcheck rule)."""
    test_dir, work_root = Path(test_dir), Path(work_root)
    work_root.mkdir(parents=True, exist_ok=True)
    available = set(list_decks(test_dir))
    names = [n for n in (only or sorted(available)) if n in available]
    dependents = {n for n in names if n in RESTART_PRODUCER or any(
        not (test_dir / d).exists() for d in _dependencies(test_dir / f"{n}.inp"))}
    first = [n for n in names if n not in dependents]
    results: dict[str, dict] = {}

    def batch(items: list[str]):
        with ThreadPoolExecutor(max_workers=workers) as ex:
            futs = {ex.submit(_run_one, n, test_dir, work_root, timeout, tol): n for n in items}
            for i, f in enumerate(as_completed(futs), 1):
                r = f.result()
                results[r["deck"]] = r
                if progress:
                    print(f"[{len(results)}/{len(names)}] {r['deck']}: {r['status']} "
                          f"({r.get('cpu_s', '?')} s)", flush=True)
                if out_json:  # checkpoint
                    _write(out_json, test_dir, results, tol)

    batch(first)
    batch(sorted(dependents))
    report = _write(out_json, test_dir, results, tol) if out_json else _summary(test_dir, results, tol)
    return report


def _summary(test_dir: Path, results: dict, tol: float) -> dict:
    counts: dict[str, int] = {}
    for r in results.values():
        counts[r["status"]] = counts.get(r["status"], 0) + 1
    return {
        "upstream": UPSTREAM,
        "ccx_version": ccx_version(),
        "criterion": f"datcheck: max |ref-val|/max|block| <= {tol}; same line count; no NaN",
        "counts": counts,
        "decks": dict(sorted(results.items())),
    }


def _write(out_json, test_dir, results, tol) -> dict:
    rep = _summary(Path(test_dir), results, tol)
    Path(out_json).write_text(json.dumps(rep, indent=1, sort_keys=False))
    return rep


def vendor(report: dict, test_dir: str | Path, dest: str | Path, select) -> list[str]:
    """Copy .inp + .dat.ref of decks satisfying ``select(record)`` into ``dest``."""
    test_dir, dest = Path(test_dir), Path(dest)
    dest.mkdir(parents=True, exist_ok=True)
    chosen = []
    for name, rec in sorted(report["decks"].items()):
        if not select(rec):
            continue
        for suffix in (".inp", ".dat.ref"):
            p = test_dir / f"{name}{suffix}"
            if p.exists():
                shutil.copy(p, dest / p.name)
        for dep in _dependencies(test_dir / f"{name}.inp"):
            if (test_dir / dep).exists():
                shutil.copy(test_dir / dep, dest / dep)
        chosen.append(name)
    return chosen
